-- Estructura PostgreSQL basada en registro_seroperfiles de XAMPP.
-- El archivo completo generado incluye esta estructura y los datos actuales.
-- Ejecutar en un proyecto donde estas dos tablas todavia no existan.
CREATE TABLE public.usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  correo varchar(160) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  rol varchar(20) NOT NULL DEFAULT 'analista'
    CHECK (rol IN ('admin', 'analista', 'consulta', 'powerbi')),
  activo smallint NOT NULL DEFAULT 1,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.seroperfiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha date NOT NULL,
  semana integer,
  trimestre integer,
  anio integer,
  razon varchar(100) DEFAULT 'Seroperfil',
  empresa varchar(120) NOT NULL,
  flujo varchar(120),
  granja varchar(180) NOT NULL,
  caseta varchar(80),
  lote varchar(100),
  funcion varchar(100),
  edad numeric(8,2),
  identidad varchar(100),
  muestra varchar(100) DEFAULT 'Suero',
  laboratorio varchar(120),
  no_caso varchar(120),
  num_muestras integer,
  enfermedad varchar(140) NOT NULL,
  tecnica varchar(100),
  resultado numeric(12,4),
  punto_corte numeric(12,4),
  interpretacion varchar(80),
  comentarios text,
  creado_por integer,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_seroperfiles_usuario FOREIGN KEY (creado_por)
    REFERENCES public.usuarios(id) ON DELETE SET NULL
);

CREATE INDEX idx_seroperfiles_creado_por ON public.seroperfiles (creado_por);
CREATE INDEX idx_fecha ON public.seroperfiles (fecha);
CREATE INDEX idx_empresa ON public.seroperfiles (empresa);
CREATE INDEX idx_flujo ON public.seroperfiles (flujo);
CREATE INDEX idx_granja ON public.seroperfiles (granja);
CREATE INDEX idx_enfermedad ON public.seroperfiles (enfermedad);
CREATE INDEX idx_laboratorio ON public.seroperfiles (laboratorio);
CREATE INDEX idx_anio_trimestre ON public.seroperfiles (anio, trimestre);

-- Equivalente de ON UPDATE CURRENT_TIMESTAMP de MySQL.
CREATE FUNCTION public.registro_rox_actualizar_timestamp()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $func$
BEGIN
  IF NEW IS DISTINCT FROM OLD
     AND NEW.actualizado_en IS NOT DISTINCT FROM OLD.actualizado_en THEN
    NEW.actualizado_en := clock_timestamp();
  END IF;
  RETURN NEW;
END;
$func$;

CREATE TRIGGER seroperfiles_actualizar_timestamp
BEFORE UPDATE ON public.seroperfiles
FOR EACH ROW EXECUTE FUNCTION public.registro_rox_actualizar_timestamp();

-- La autenticacion actual vive en Express. No habilitar acceso publico
-- directo a los usuarios, sus hashes o los registros desde el navegador.
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.seroperfiles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.usuarios, public.seroperfiles FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.usuarios_id_seq, public.seroperfiles_id_seq FROM PUBLIC;
REVOKE ALL ON FUNCTION public.registro_rox_actualizar_timestamp() FROM PUBLIC;
DO $seguridad$
DECLARE
  nombre_rol text;
BEGIN
  FOREACH nombre_rol IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = nombre_rol) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.usuarios, public.seroperfiles FROM %I', nombre_rol);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.usuarios_id_seq, public.seroperfiles_id_seq FROM %I', nombre_rol);
      EXECUTE format('REVOKE ALL ON FUNCTION public.registro_rox_actualizar_timestamp() FROM %I', nombre_rol);
    END IF;
  END LOOP;
END;
$seguridad$;
